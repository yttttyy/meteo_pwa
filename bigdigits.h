// ============================================================
//   БОЛЬШИЕ ЦИФРЫ (порт из AlexGyver MeteoClock)
// ============================================================
// Два шрифта больших цифр, оба укладываются в 8 слотов CGRAM вместе
// с точкой двоеточия и градусом (на кириллическом ROM их нет, поэтому свои).
// ⚠️ 0xFF на кириллическом ROM — НЕ сплошной блок, освобождать CGRAM заменой
// углов на 255 нельзя — цифры разваливаются. Только свои 8 символов.
// Слоты: 0 - вертикаль (палка FB / скруглённая сверху CT), 3 - низ скруглён CB.

// Общие сегменты (одинаковы в обоих шрифтах):
uint8_t UB[8]  = {0b11111, 0b11111, 0b11111, 0b00000, 0b00000, 0b00000, 0b00000, 0b00000};
uint8_t LB[8]  = {0b00000, 0b00000, 0b00000, 0b00000, 0b00000, 0b11111, 0b11111, 0b11111};
uint8_t UMB[8] = {0b11111, 0b11111, 0b11111, 0b00000, 0b00000, 0b00000, 0b11111, 0b11111};
uint8_t LMB[8] = {0b11111, 0b00000, 0b00000, 0b00000, 0b00000, 0b11111, 0b11111, 0b11111};
uint8_t DOT[8] = {0b00000, 0b00000, 0b00000, 0b01100, 0b01100, 0b00000, 0b00000, 0b00000};  // точка 2x2 по центру — как символ 165 у Гайвера
uint8_t DEG[8] = {0b01100, 0b10010, 0b10010, 0b01100, 0b00000, 0b00000, 0b00000, 0b00000};  // градус 4x4, внутри 2x2 пусто — как символ 223
// Сегменты под конкретный шрифт:
uint8_t FB[8]  = {0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111};  // палка
uint8_t CT[8]  = {0b01110, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111};  // колонка, скруглена сверху
uint8_t CB[8]  = {0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b11111, 0b01110};  // колонка, скруглена снизу
// Стрелки тренда. На экране их всегда не больше одной, поэтому обе живут
// в одном слоте: при смене тренда символ просто переписывается.
uint8_t ARR_UP[8] = {0b00000, 0b00100, 0b01110, 0b11111, 0b00100, 0b00100, 0b00100, 0b00000};
uint8_t ARR_DN[8] = {0b00000, 0b00100, 0b00100, 0b00100, 0b11111, 0b01110, 0b00100, 0b00000};

int8_t arrowLoaded = 0;   // что сейчас в слоте CH_ARROW: 0 — не наша графика, ±1 — стрелка

void loadFont(uint8_t f) {
  lcd.createChar(1, UB);
  lcd.createChar(CH_DOT, DOT);
  lcd.createChar(4, LB);
  lcd.createChar(DEGREE_CHAR, DEG);
  lcd.createChar(6, UMB);
  lcd.createChar(7, LMB);
  if (f == FONT_ROUND) {
    lcd.createChar(0, CT);   // верх скруглён
    lcd.createChar(3, CB);   // низ скруглён
  } else {
    lcd.createChar(0, FB);   // сплошная палка (слот 3 свободен — уходит под стрелку)
  }
  arrowLoaded = 0;           // слот мог быть перезаписан под CB, стрелку грузим заново
}

// Положить в слот нужную стрелку. В скруглённом шрифте слот занят под CB —
// там стрелки нет, drawSensors падает на ASCII.
void loadArrow(int8_t dir) {
  if (font != FONT_RECT || dir == 0 || dir == arrowLoaded) return;
  lcd.createChar(CH_ARROW, dir > 0 ? ARR_UP : ARR_DN);
  arrowLoaded = dir;
}

// сегменты цифр: 3 ячейки верхней строки + 3 нижней (32 = пробел).
// [0] - палки (низ вертикалей берёт слот 0=FB),
// [1] - скруглённый (низ вертикалей берёт слот 3=CB)
const uint8_t digSeg[2][10][6] = {
  { // FONT_RECT
    {0,  1, 0, 0,  4,  0 },  // 0
    {32, 32, 0, 32, 32, 0 },  // 1  (просто вертикальная палка, без флажка)
    {6,  6, 0, 0,  7,  7 },  // 2
    {6,  6, 0, 7,  7,  0 },  // 3
    {0,  4, 0, 32, 32, 0 },  // 4
    {0,  6, 6, 7,  7,  0 },  // 5
    {0,  6, 6, 0,  7,  0 },  // 6
    {1,  1, 0, 32, 0,  32},  // 7
    {0,  6, 0, 0,  7,  0 },  // 8
    {0,  6, 0, 4,  4,  0 },  // 9  (низ слева добавлен — полная нижняя перекладина)
  },
  { // FONT_ROUND
    {0,  1, 0, 3,  4,  3 },  // 0
    {32, 32, 0, 32, 32, 3 },  // 1
    {6,  6, 0, 3,  7,  7 },  // 2
    {6,  6, 0, 7,  7,  3 },  // 3
    {3,  4, 0, 32, 32, 3 },  // 4
    {0,  6, 6, 7,  7,  3 },  // 5
    {0,  6, 6, 3,  7,  3 },  // 6
    {1,  1, 0, 32, 0,  32},  // 7
    {0,  6, 0, 3,  7,  3 },  // 8
    {0,  6, 0, 4,  4,  3 },  // 9
  },
};
